#!/usr/bin/env python3
"""Build docs/learn-and-pitch/TRINC-learn-and-pitch-pack.md from the numbered parts.

The combined file is what gets uploaded to a claude.ai Project in one go. It is generated, never edited by
hand, so it cannot drift from the parts.

    python3 scripts/build-learn-and-pitch-pack.py           # write the combined file
    python3 scripts/build-learn-and-pitch-pack.py --check   # exit 1 if it is stale
"""
import pathlib
import sys

PACK = pathlib.Path(__file__).resolve().parent.parent / "docs" / "learn-and-pitch"
OUT = PACK / "TRINC-learn-and-pitch-pack.md"
# 00-in-my-own-words.md is the operator's own writing, not part of the upload.
SKIP = {"00-in-my-own-words.md"}

HEADER = (
    "# TRINC learn-and-pitch pack (combined)\n\n"
    "> Generated by `scripts/build-learn-and-pitch-pack.py` from the files in `docs/learn-and-pitch/`.\n"
    "> Do not edit this file; edit the parts and rebuild. Start with part 00: it holds the rules.\n"
)


def parts():
    return sorted(p for p in PACK.glob("[0-9][0-9]-*.md") if p.name not in SKIP)


def render():
    chunks = [HEADER]
    for p in parts():
        chunks.append(f"\n\n---\n\n<!-- part: {p.name} -->\n\n" + p.read_text(encoding="utf-8").strip() + "\n")
    return "".join(chunks)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT} differs from its parts; rebuild it.")
            return 1
        print(f"OK: {OUT.name} matches {len(parts())} parts.")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT} from {len(parts())} parts ({len(text):,} characters).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
