"use strict";

/**
 * Obsidian formatter — converts graph analysis output into Obsidian-compatible
 * markdown with wikilinks, Dataview properties, and tag suggestions.
 *
 * @module obsidian-formatter
 */

/**
 * Format graph analysis results as Obsidian markdown.
 *
 * @param {object} analysisResult - Output from any Zettelkasten command
 * @param {object} [options]
 * @param {string} [options.noteTitle] - Title for the output note
 * @returns {string} Obsidian-compatible markdown
 */
function formatForObsidian(analysisResult, options) {
  const opts = options || {};
  const title = opts.noteTitle || "Graph Analysis";
  const parts = [];

  parts.push(`# ${title}\n`);
  parts.push(`> Generated by Medical Zettelkasten MCP\n`);

  // Cross-domain connections
  if (analysisResult.cross_domain) {
    parts.push(formatCrossDomain(analysisResult.cross_domain));
  }

  // Echo chamber analysis
  if (analysisResult.echo_chamber) {
    parts.push(formatEchoChamber(analysisResult.echo_chamber));
  }

  // Semantic links
  if (analysisResult.semantic_links) {
    parts.push(formatSemanticLinks(analysisResult.semantic_links));
  }

  // Orphan rescue
  if (analysisResult.orphan_rescue) {
    parts.push(formatOrphanRescue(analysisResult.orphan_rescue));
  }

  // Serendipity
  if (analysisResult.serendipity) {
    parts.push(formatSerendipity(analysisResult.serendipity));
  }

  // Standalone results (when called per-tool)
  if (analysisResult.bridges) parts.push(formatCrossDomain(analysisResult));
  if (analysisResult.diversity_score !== undefined && !analysisResult.cross_domain) {
    parts.push(formatEchoChamber(analysisResult));
  }
  if (analysisResult.direct_links) parts.push(formatSemanticLinks(analysisResult));
  if (analysisResult.orphan_nodes && !analysisResult.cross_domain) {
    parts.push(formatOrphanRescue(analysisResult));
  }
  if (analysisResult.lateral_prompts && !analysisResult.cross_domain) {
    parts.push(formatSerendipity(analysisResult));
  }

  return parts.filter(Boolean).join("\n");
}

function formatCrossDomain(data) {
  const lines = ["## Cross-Domain Connections\n"];
  if (data.connection_proposals) {
    for (const cp of data.connection_proposals) {
      lines.push(`- [[${cp.concept_a}]] ↔ [[${cp.concept_b}]] — ${cp.relationship_type}`);
      lines.push(`  - Confidence: ${cp.confidence}`);
    }
  }
  if (data.universal_principles) {
    lines.push("\n### Tags");
    for (const p of data.universal_principles) {
      lines.push(`- ${p.tag}`);
    }
  }
  return lines.join("\n") + "\n";
}

function formatEchoChamber(data) {
  const lines = ["## Bias Assessment\n"];
  lines.push(`- Diversity Score: **${data.diversity_score}**`);
  if (data.bias_assessment) {
    lines.push(`- Dominant Cluster: ${data.bias_assessment.dominant_cluster} (${data.bias_assessment.dominance_ratio * 100}%)`);
  }
  if (data.challenge_questions) {
    lines.push("\n### Challenge Questions");
    for (const q of data.challenge_questions) {
      lines.push(`- ${q.question}`);
    }
  }
  return lines.join("\n") + "\n";
}

function formatSemanticLinks(data) {
  const lines = ["## Semantic Relationships\n"];
  if (data.direct_links) {
    for (const link of data.direct_links.slice(0, 20)) {
      lines.push(`- [[${link.source}]] → [[${link.target}]]`);
      lines.push(`  - ${link.type}:: [[${link.target}]]`);
    }
  }
  if (data.hidden_links && data.hidden_links.length > 0) {
    lines.push("\n### Hidden Links");
    for (const hl of data.hidden_links) {
      lines.push(`- [[${hl.source}]] ↔ [[${hl.target}]] (via ${hl.intermediaries.map((i) => `[[${i}]]`).join(", ")})`);
    }
  }
  return lines.join("\n") + "\n";
}

function formatOrphanRescue(data) {
  const lines = ["## Orphan Rescue\n"];
  if (data.orphan_nodes) {
    lines.push(`Found **${data.orphan_nodes.length}** orphan concepts.\n`);
  }
  if (data.rescue_proposals) {
    for (const rp of data.rescue_proposals) {
      lines.push(`- [[${rp.orphan}]] → connect to [[${rp.bridge_concept}]]`);
      lines.push(`  - ${rp.rationale}`);
    }
  }
  return lines.join("\n") + "\n";
}

function formatSerendipity(data) {
  const lines = ["## Serendipitous Discoveries\n"];
  if (data.lateral_prompts) {
    for (const lp of data.lateral_prompts) {
      lines.push(`> ${lp.prompt}\n`);
    }
  }
  if (data.serendipitous_connections) {
    lines.push("### Unexpected Connections");
    for (const sc of data.serendipitous_connections) {
      lines.push(`- [[${sc.concept_a}]] ↔ [[${sc.concept_b}]] (surprise: ${sc.surprise_score})`);
    }
  }
  return lines.join("\n") + "\n";
}

/**
 * Extract all unique concept names as wikilinks.
 * @param {object} analysisResult
 * @returns {string[]}
 */
function extractWikilinks(analysisResult) {
  const links = new Set();
  const json = JSON.stringify(analysisResult);
  // Extract node labels, concept names, etc.
  const str = JSON.stringify(analysisResult, null, 2);
  const patterns = [/"source":\s*"([^"]+)"/g, /"target":\s*"([^"]+)"/g, /"label":\s*"([^"]+)"/g, /"concept_a":\s*"([^"]+)"/g, /"concept_b":\s*"([^"]+)"/g];
  for (const pattern of patterns) {
    let match;
    while ((match = pattern.exec(str)) !== null) {
      links.add(match[1]);
    }
  }
  return Array.from(links).sort();
}

module.exports = { formatForObsidian, extractWikilinks };
