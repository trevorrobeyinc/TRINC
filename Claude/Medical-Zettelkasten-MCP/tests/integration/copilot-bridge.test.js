"use strict";

const { describe, it } = require("node:test");
const assert = require("node:assert/strict");
const { dispatch } = require("../../src/handlers/index.js");
const { createCopilotBridge } = require("../../lib/copilot-bridge.js");
const { formatForObsidian, extractWikilinks } = require("../../lib/obsidian-formatter.js");

const SAMPLE_TEXT = "Aspirin reduces inflammation and pain through COX inhibition. Metformin activates AMPK for diabetes. Cancer research investigates both drugs.";

describe("Copilot bridge adapter", () => {
  it("toCopilotResponse returns valid format", async () => {
    const result = await dispatch("full_zettelkasten_analysis", { text: SAMPLE_TEXT });
    const data = JSON.parse(result.content[0].text);
    const bridge = createCopilotBridge({ vaultName: "TestVault" });
    const response = bridge.toCopilotResponse(data, "full_zettelkasten_analysis");

    assert.ok(response.ok);
    assert.equal(response.command, "full_zettelkasten_analysis");
    assert.ok(response.content.length > 0);
    assert.ok(Array.isArray(response.suggestions));
    assert.equal(response.metadata.vault, "TestVault");
  });

  it("toObsidianNote returns markdown", async () => {
    const result = await dispatch("full_zettelkasten_analysis", { text: SAMPLE_TEXT });
    const data = JSON.parse(result.content[0].text);
    const bridge = createCopilotBridge();
    const note = bridge.toObsidianNote(data, "Test Analysis");

    assert.ok(note.includes("# Test Analysis"));
    assert.ok(note.includes("Generated by Medical Zettelkasten MCP"));
  });
});

describe("Obsidian formatter", () => {
  it("formats with wikilinks", async () => {
    const result = await dispatch("cross_domain_connect", { text: SAMPLE_TEXT });
    const data = JSON.parse(result.content[0].text);
    const markdown = formatForObsidian(data, { noteTitle: "Test" });
    assert.ok(markdown.includes("[["));
  });

  it("extracts wikilinks from analysis", async () => {
    const result = await dispatch("full_zettelkasten_analysis", { text: SAMPLE_TEXT });
    const data = JSON.parse(result.content[0].text);
    const links = extractWikilinks(data);
    assert.ok(links.length > 0);
    assert.ok(Array.isArray(links));
  });
});
