"use strict";

/**
 * render-business-context — the DERIVED block of the vault's canonical Copilot business-context
 * note, generated from live config (2026-09-22, Obsidian re-integration plan, decision D7).
 *
 * WHY. `/Users/myhome/My Digital Garden/Trevor Robey Inc/Business Context — Trevor Robey INC.md`
 * carries `copilot-context: canonical`, so Obsidian Copilot answers business questions from it. It is
 * a hand-written note that nothing propagates into; it was found three weeks stale with six factual
 * errors on 2026-07-27 and stale again (Ollama, the git remote, the sources, the channels) on
 * 2026-09-22. Its own §8 ranks live config above prose. This script renders the facts that live
 * config can vouch for — LLM routing, research sources by adapter status, evidence prefetch per role,
 * distribution/content channels and their manual-only flags, the engine→vault pipeline switches, the
 * offering ladder COPIED BYTE-FOR-BYTE from OFFERINGS.md (a price is never computed here), and the
 * legal-entity rows COPIED from the certificate record — as one block between markers. The prose
 * sections stay hand-maintained.
 *
 * NEVER AUTOMATIC. `--apply` writes the vault note; it is meant to be run by the operator (or on the
 * operator's go), never from a commit hook or a timer: a bad auto-write becomes a confidently wrong
 * Copilot answer. `--check` is the drift tripwire (exit 1 when the note's block differs from live
 * config); `--print` renders the block to stdout.
 *
 * Usage:
 *   node scripts/render-business-context.js --print
 *   node scripts/render-business-context.js --check [--note <abs path>]
 *   node scripts/render-business-context.js --apply [--note <abs path>]
 */

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const MARK_BEGIN = "<!-- derived:begin — generated by scripts/render-business-context.js from live config; do not hand-edit inside these markers -->";
const MARK_END = "<!-- derived:end -->";
const DEFAULT_NOTE = "/Users/myhome/My Digital Garden/Trevor Robey Inc/Business Context — Trevor Robey INC.md";
const INSERT_BEFORE = /^## 1\. /m;

function readJson(rel, rootDir = ROOT) {
  return JSON.parse(fs.readFileSync(path.join(rootDir, rel), "utf8"));
}

function readText(rel, rootDir = ROOT) {
  return fs.readFileSync(path.join(rootDir, rel), "utf8");
}

/** Lines of one `## heading` section of a markdown file, verbatim (heading excluded). */
function sectionLines(markdown, heading) {
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.trim() === heading.trim());
  if (start < 0) return [];
  const out = [];
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^## /.test(lines[i])) break;
    out.push(lines[i]);
  }
  while (out.length && out[out.length - 1].trim() === "") out.pop();
  while (out.length && out[0].trim() === "") out.shift();
  return out;
}

/** Table rows (verbatim) whose first cell matches one of the wanted labels. */
function tableRows(markdown, wantedLabels) {
  const rows = [];
  for (const line of markdown.split("\n")) {
    if (!/^\|/.test(line)) continue;
    const first = line.split("|")[1] || "";
    const label = first.replace(/\*\*/g, "").trim();
    if (wantedLabels.some((w) => label.toLowerCase().startsWith(w.toLowerCase()))) rows.push(line);
  }
  return rows;
}

function renderDerivedBlock(rootDir = ROOT) {
  const routing = readJson("config/role-provider-map.json", rootDir);
  const registry = readJson("config/connector-registry.json", rootDir);
  const prefetch = readJson("config/tool-prefetch-map.json", rootDir);
  const targets = readJson("config/platform-targets.json", rootDir);
  const vaultPublish = readJson("config/vault-publish.json", rootDir);
  const offerings = readText("OFFERINGS.md", rootDir);
  const certificate = readText("00-business-formation/llc/certificate-of-formation.md", rootDir);

  const L = [];
  L.push(MARK_BEGIN);
  L.push("");
  L.push("## 0. Live-config snapshot (generated — the facts config can vouch for)");
  L.push("");
  L.push("> Rendered by `scripts/render-business-context.js` from the engine's live config files, so these lines cannot drift from the code that runs. Prices are copied verbatim from `OFFERINGS.md`, entity rows from the certificate record — nothing here is computed or invented. Re-run with `--check` to detect drift, `--apply` to refresh (operator-run only).");
  L.push("");

  // 1. LLM routing
  L.push("### LLM routing (`config/role-provider-map.json`)");
  L.push("");
  L.push("| Role | Provider | Model | Fallback |");
  L.push("|---|---|---|---|");
  for (const [role, v] of Object.entries(routing.roles || {})) {
    L.push(`| ${role} | \`${v.provider}\` | \`${v.model}\` | ${v.fallback ? `\`${v.fallback}\`` : "none"} |`);
  }
  if (routing.default) {
    L.push(`| *default / unmapped* | \`${routing.default.provider}\` | \`${routing.default.model}\` | ${routing.default.fallback ? `\`${routing.default.fallback}\`` : "none"} |`);
  }
  L.push("");

  // 2. Research sources by status + lane
  const connectors = Object.entries(registry.connectors || {});
  const byLane = {};
  for (const [id, e] of connectors) {
    const lane = e.lane || "(unlaned)";
    byLane[lane] = byLane[lane] || {};
    const st = e.adapter_status || "(unset)";
    byLane[lane][st] = byLane[lane][st] || [];
    byLane[lane][st].push(id);
  }
  L.push("### Research sources (`config/connector-registry.json`)");
  L.push("");
  L.push(`Registered connectors: **${connectors.length}**. Only the \`research\` lane may feed evidence into a run; \`vault\`-lane read-back is context only, never citation evidence.`);
  L.push("");
  L.push("| Lane | Adapter status | Count | Connectors |");
  L.push("|---|---|---|---|");
  for (const lane of Object.keys(byLane).sort()) {
    for (const st of Object.keys(byLane[lane]).sort()) {
      const ids = byLane[lane][st].sort();
      L.push(`| ${lane} | ${st} | ${ids.length} | ${ids.join(", ")} |`);
    }
  }
  L.push("");

  // 3. Evidence prefetch per role
  const roleMap = prefetch.role_mappings || {};
  const allTools = new Set();
  L.push("### Evidence prefetch per role (`config/tool-prefetch-map.json`)");
  L.push("");
  L.push("Retrieval happens before any prompt exists, from this static table — the model never chooses what to fetch. Entries marked *context-only* inform the role but never ground a citation.");
  L.push("");
  L.push("| Role | Sources | Context-only |");
  L.push("|---|---|---|");
  for (const [role, entries] of Object.entries(roleMap)) {
    if (!Array.isArray(entries)) continue;
    const names = entries.map((e) => e.tool_name || e.action).filter(Boolean);
    for (const n of names) allTools.add(n);
    const ctx = entries.filter((e) => e.context_only === true).map((e) => e.tool_name);
    L.push(`| ${role} | ${names.length}: ${names.join(", ")} | ${ctx.length ? ctx.join(", ") : "—"} |`);
  }
  L.push("");
  L.push(`Distinct prefetch sources across all roles: **${allTools.size}**.`);
  L.push("");

  // 4. Channels
  const pt = targets.platform_targets || {};
  const entries = Array.isArray(pt) ? pt : Object.entries(pt).map(([id, v]) => ({ id, ...(v || {}) }));
  L.push("### Distribution & content channels (`config/platform-targets.json`)");
  L.push("");
  L.push("| Target | Manual-only (schema-enforced) |");
  L.push("|---|---|");
  for (const t of entries.sort((a, b) => String(a.id).localeCompare(String(b.id)))) {
    L.push(`| ${t.id} | ${t.manual_only === true ? "yes" : "**NO**"} |`);
  }
  L.push("");
  L.push(`${entries.length} targets; ${entries.filter((t) => t.manual_only === true).length} manual-only. The engine's submission lane is structurally incapable of autonomous publishing (\`offer-schema.js\` throws on any target whose \`manual_only\` is not true).`);
  L.push("");

  // 5. Engine → vault pipeline switches
  const rm = vaultPublish.researchMemory || {};
  const ga = vaultPublish.graphAnalysis || {};
  L.push("### Engine → Obsidian pipeline (`config/vault-publish.json`)");
  L.push("");
  L.push("| Switch | Value |");
  L.push("|---|---|");
  L.push(`| Engine writes vault notes after a gate-PASS run (headless) | ${vaultPublish.enabled === true ? "on" : "off"} |`);
  L.push(`| Vault folder scheme | \`${vaultPublish.vaultOutputFolder || "OpenClaw"}/<template>/<date> <inputs>/\` |`);
  L.push(`| Deliverables mirrored verbatim into the vault | ${(vaultPublish.deliverables || []).join(", ") || "none"} |`);
  L.push(`| Deterministic graph analysis note (Medical Zettelkasten MCP, no LLM) | ${ga.enabled === true ? "on" : "off"} |`);
  L.push(`| Research-memory ingest + priors (Qdrant via :6433) | ${rm.enabled === true ? "on" : "off (operator must let the CLI fetch its embedding model once, then enable)"} |`);
  L.push("");

  // 6. Offering ladder — verbatim
  const ladder = sectionLines(offerings, "## Offering Ladder");
  L.push("### Offering ladder (copied verbatim from `OFFERINGS.md` → \"Offering Ladder\")");
  L.push("");
  if (ladder.length) L.push(...ladder);
  else L.push("*(OFFERINGS.md has no \"## Offering Ladder\" section — nothing copied; never computed.)*");
  L.push("");

  // 6b. Business research tiers — verbatim, with their booking gate and guarantee scope
  const business = sectionLines(offerings, "## Business research (any field)");
  L.push("### Business research tiers (copied verbatim from `OFFERINGS.md` → \"Business research (any field)\")");
  L.push("");
  if (business.length) L.push(...business);
  else L.push("*(OFFERINGS.md has no \"## Business research (any field)\" section — nothing copied; never computed.)*");
  L.push("");

  // 7. Legal entity — verbatim rows
  const rows = tableRows(certificate, ["Legal entity name", "Filing date", "Approval status", "California Entity No", "Certified copy"]);
  L.push("### Legal entity (rows copied verbatim from `00-business-formation/llc/certificate-of-formation.md`)");
  L.push("");
  if (rows.length) {
    L.push("| Field | Value |");
    L.push("|---|---|");
    L.push(...rows);
  } else {
    L.push("*(certificate record has no matching rows — nothing copied.)*");
  }
  L.push("");
  L.push(MARK_END);
  return L.join("\n");
}

function spliceBlock(noteText, block, today) {
  let out = noteText;
  const b = out.indexOf(MARK_BEGIN);
  const e = out.indexOf(MARK_END);
  if (b >= 0 && e > b) {
    out = out.slice(0, b) + block + out.slice(e + MARK_END.length);
  } else {
    const m = out.match(INSERT_BEFORE);
    if (!m || m.index === undefined) throw new Error("note has no '## 1. ' heading to insert before");
    out = out.slice(0, m.index) + block + "\n\n---\n\n" + out.slice(m.index);
  }
  if (today) {
    out = out.replace(/^last-verified:\s*.*$/m, `last-verified: ${today}`);
  }
  return out;
}

function currentBlock(noteText) {
  const b = noteText.indexOf(MARK_BEGIN);
  const e = noteText.indexOf(MARK_END);
  if (b < 0 || e < b) return null;
  return noteText.slice(b, e + MARK_END.length);
}

function guardNotePath(notePath, allowedRoots) {
  const real = fs.realpathSync(notePath);
  const ok = allowedRoots.some((root) => {
    let r;
    try { r = fs.realpathSync(root); } catch { return false; }
    return real === r || real.startsWith(r + path.sep);
  });
  if (!ok) throw new Error(`note is outside every allowed vault root: ${notePath}`);
  return real;
}

function parseArgs(argv) {
  const out = { print: false, check: false, apply: false, note: DEFAULT_NOTE, unknown: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const t = String(argv[i] || "");
    if (t === "--print") { out.print = true; continue; }
    if (t === "--check") { out.check = true; continue; }
    if (t === "--apply") { out.apply = true; continue; }
    if (t === "--note") { out.note = String(argv[i + 1] || ""); i += 1; continue; }
    out.unknown.push(t);
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const modes = [args.print, args.check, args.apply].filter(Boolean).length;
  if (args.unknown.length || modes !== 1) {
    process.stderr.write("Usage: node scripts/render-business-context.js (--print | --check | --apply) [--note <abs path>]\n");
    return 2;
  }
  const block = renderDerivedBlock(ROOT);
  if (args.print) {
    process.stdout.write(`${block}\n`);
    return 0;
  }
  const vaultPublish = readJson("config/vault-publish.json", ROOT);
  const allowed = Array.isArray(vaultPublish.allowedVaultRoots) ? vaultPublish.allowedVaultRoots : [];
  const notePath = guardNotePath(args.note, allowed);
  const noteText = fs.readFileSync(notePath, "utf8");
  const existing = currentBlock(noteText);
  if (args.check) {
    if (existing === null) {
      process.stderr.write("DRIFT: the note has no derived block yet (run --apply)\n");
      return 1;
    }
    if (existing !== block) {
      process.stderr.write("DRIFT: the note's derived block differs from live config (run --apply)\n");
      return 1;
    }
    process.stdout.write("OK: derived block matches live config\n");
    return 0;
  }
  const today = new Date().toISOString().slice(0, 10);
  const next = spliceBlock(noteText, block, today);
  if (next === noteText) {
    process.stdout.write("no change\n");
    return 0;
  }
  const tmp = `${notePath}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, next, "utf8");
  fs.renameSync(tmp, notePath);
  process.stdout.write(`${existing === null ? "inserted" : "refreshed"} derived block; last-verified → ${today}\n`);
  return 0;
}

if (require.main === module) {
  try {
    // exitCode, not process.exit(): a piped stdout is asynchronous, and exiting immediately after a
    // multi-KB write truncates the block for whoever is reading it.
    process.exitCode = main();
  } catch (err) {
    process.stderr.write(`${err && err.stack ? err.stack : String(err)}\n`);
    process.exitCode = 1;
  }
}

module.exports = { renderDerivedBlock, spliceBlock, currentBlock, sectionLines, tableRows, MARK_BEGIN, MARK_END };
